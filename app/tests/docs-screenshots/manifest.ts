export type DocsScreenshotAction =
  | { type: 'click'; selector: string }
  | { type: 'fill'; selector: string; value: string; sensitive?: boolean }
  | { type: 'press'; key: string }
  | { type: 'hover'; selector: string }
  | { type: 'waitFor'; selector: string }
  | { type: 'callHelper'; name: string; args?: Record<string, unknown> };

export type DocsScreenshotAnnotation = {
  selector: string;
  /** 'marker' is the style-guide numbered circle; the other modes are legacy. */
  mode: 'box' | 'dot' | 'callout' | 'marker';
  label?: string;
  number?: number;
  offsetX?: number;
  offsetY?: number;
  /** marker only: pick the first visible match whose text contains this string. */
  hasText?: string;
  /** marker only: index among the visible matches (default 0). */
  nth?: number;
  /** marker only: where the circle sits relative to the target (default 'left'). */
  placement?: 'left' | 'right' | 'top' | 'bottom' | 'top-left';
  /** marker only: draw the 2 px outline around the target (default true). */
  outline?: boolean;
};

export type DocsScreenshot = {
  slug: string;
  output: string;
  docRefs: string[];
  route?: string;
  url?: string;
  /** 'public' captures read-only public pages from the live site (real records, no fixtures). */
  baseURL?: 'app' | 'api' | 'public' | string;
  viewport: { width: number; height: number };
  authRole?: 'admin' | 'curator' | 'reviewer' | 'user';
  preSetup?: string;
  setup?: string;
  actions?: DocsScreenshotAction[];
  waitFor?: string;
  locator?: string;
  fullPage?: boolean;
  clip?: { x: number; y: number; width: number; height: number };
  /** Clip the page to an element's box plus padding (room for markers placed beside it). */
  clipTo?: { selector: string; hasText?: string; padding?: number; maxHeight?: number };
  maskSelectors?: string[];
  annotations?: DocsScreenshotAnnotation[];
};

